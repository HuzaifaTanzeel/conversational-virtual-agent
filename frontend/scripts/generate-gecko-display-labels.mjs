/**
 * Generates geckoDisplayLabels.js from vendored Gecko tour XML.
 * Display labels only — navigation targets come from sceneRegistry.js.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const tourPath = path.join(root, "public/vt/icmaldives/tour.xml");
const scenesPath = path.join(root, "public/vt/icmaldives/scenes.xml");
const outPath = path.join(root, "src/lib/geckoDisplayLabels.js");

/** Registry-only rooms omitted from Gecko lmenus — use Gecko naming style. */
const DISPLAY_LABEL_OVERRIDES = {
  scene_TwoBedroomBeachfrontResidence_TwinBathroom: "SECOND BATHROOM",
  scene_TwoBedroomLagoonPoolVilla_Bathroom: "MASTER BATHROOM",
};

const tour = fs.readFileSync(tourPath, "utf8");
const scenesXml = fs.readFileSync(scenesPath, "utf8");

/** @type {Record<string, string>} */
const labels = {};

function setLabel(sceneId, label, source) {
  if (!sceneId || !label?.trim()) return;
  const key = sceneId.trim();
  const value = label.trim().toUpperCase();
  if (!labels[key]) {
    labels[key] = value;
  }
}

// 1. tour.xml l_menu html (primary — villa sidemenus)
for (const m of tour.matchAll(
  /<layer style="l_menu"[^>]*html="([^"]+)"[^>]*linkedscene="(scene_[^"]+)"/g,
)) {
  setLabel(m[2], m[1], "l_menu");
}
for (const m of tour.matchAll(
  /<layer style="l_menu"[^>]*linkedscene="(scene_[^"]+)"[^>]*html="([^"]+)"/g,
)) {
  setLabel(m[1], m[2], "l_menu");
}

// 2. tour.xml nav_submenu_text (dining, aerial, accommodation bar)
for (const m of tour.matchAll(
  /<layer style="nav_submenu_text"[^>]*html="([^"]+)"[^>]*linkedscene="(scene_[^"]+)"/g,
)) {
  setLabel(m[2], m[1], "nav_submenu");
}
for (const m of tour.matchAll(
  /<layer style="nav_submenu_text"[^>]*linkedscene="(scene_[^"]+)"[^>]*html="([^"]+)"/g,
)) {
  setLabel(m[1], m[2], "nav_submenu");
}

// 3. scenes.xml title — suffix after " / "
for (const m of scenesXml.matchAll(/<scene name="(scene_[^"]+)" title="([^"]+)"/g)) {
  const sceneId = m[1];
  const title = m[2];
  const slashIdx = title.indexOf(" / ");
  const roomPart = slashIdx >= 0 ? title.slice(slashIdx + 3) : title;
  setLabel(sceneId, roomPart, "scenes_title");
}

// 4. Manual overrides (registry-only rooms)
for (const [sceneId, label] of Object.entries(DISPLAY_LABEL_OVERRIDES)) {
  labels[sceneId] = label;
}

// Normalize a few scenes.xml title fallbacks to match Gecko l_menu shorthand
const SHORTHAND = {
  scene_Aerial_ThreeBedOverwaterVilla: "AERIAL",
  scene_Aerial_Lagoon: "LAGOON",
  scene_Aerial_Lighthouse: "LIGHTHOUSE BEACH",
  scene_Aerial_MainPool: "MAIN POOL",
  scene_Aerial_ResortOverview: "RESORT OVERVIEW",
  scene_Aerial_SunsetBar: "SUNSET BAR",
  scene_MainPool: "MAIN POOL",
  scene_RetreatSwimmingPool: "RETREAT POOL",
  scene_FishMarket: "FISH MARKET",
  scene_Lighthouse: "LIGHTHOUSE",
  scene_Umi: "CAFÉ UMI",
  scene_PlanetCheckers_Interior: "INDOOR",
  scene_PlanetCheckers_Exterior: "OUTDOOR",
  scene_Spa_RelaxationLounge: "RELAXATION LOUNGE",
  scene_Spa_TreatmentRoom: "TREATMENT ROOM",
};
for (const [sceneId, label] of Object.entries(SHORTHAND)) {
  labels[sceneId] = label;
}

const sortedKeys = Object.keys(labels).sort();
const lines = sortedKeys.map((k) => `  "${k}": ${JSON.stringify(labels[k])},`).join("\n");

const output = `/**
 * AUTO-GENERATED by scripts/generate-gecko-display-labels.mjs — do not edit by hand.
 * Run: npm run generate:gecko-labels
 *
 * Gecko short display names keyed by krpanoSceneId. Navigation uses sceneRegistry.js.
 */

/** @type {Record<string, string>} */
export const GECKO_DISPLAY_LABELS = {
${lines}
};

/** Manual overrides applied at generation time (registry-only rooms). */
export const DISPLAY_LABEL_OVERRIDES = ${JSON.stringify(DISPLAY_LABEL_OVERRIDES, null, 2)};

/**
 * @param {string} krpanoSceneId
 * @returns {string}
 */
export function getDisplayLabel(krpanoSceneId) {
  const id = (krpanoSceneId || "").trim();
  if (!id) return "";
  return GECKO_DISPLAY_LABELS[id] ?? id.replace(/^scene_/, "").replace(/_/g, " ").toUpperCase();
}
`;

fs.writeFileSync(outPath, output, "utf8");
console.log(`Wrote ${outPath} (${sortedKeys.length} labels)`);
